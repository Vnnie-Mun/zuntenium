# zuntenium/ai_engine/decision.py
"""
AIDecision dataclass — the fully-typed, explainable output of AIOptimizer.select().

Every field is mandatory and documented.  No black-box outputs.
"""

from __future__ import annotations

import time
from dataclasses import dataclass, field
from enum import Enum
from typing import Any


# ---------------------------------------------------------------------------
# Enumerations for type-safety
# ---------------------------------------------------------------------------

class BackendChoice(str, Enum):
    """Canonical backend identifiers used across the entire Zuntenium stack."""
    STATEVECTOR   = "statevector"
    TENSORNETWORK = "tensornetwork"
    STABILIZER    = "stabilizer"
    IBM           = "ibm"
    UNKNOWN       = "unknown"


class TranspilationStrategy(str, Enum):
    """
    Transpilation strategy levels:

    NONE        — pass circuit through as-is (e.g. already optimised externally)
    RULE_ONLY   — deterministic rule-based passes (QubitMapping, SWAP, Decompose)
    RL_REFINE   — rule passes followed by PPO RL refinement
    HARDWARE    — full hardware-aware stack (mapping + SWAP + decompose + noise)
    """
    NONE          = "none"
    RULE_ONLY     = "rule_only"
    RL_REFINE     = "rl_refine"
    HARDWARE      = "hardware_aware"


class DecisionSource(str, Enum):
    """Which component produced this decision (for audit trail)."""
    AI_SUPERVISED = "ai_supervised"
    AI_RL         = "ai_rl"
    RULE_FALLBACK = "rule_fallback"
    EMERGENCY     = "emergency_fallback"


# ---------------------------------------------------------------------------
# AIDecision
# ---------------------------------------------------------------------------

@dataclass
class AIDecision:
    """
    The complete, explainable decision returned by AIOptimizer.select().

    All downstream components (HybridExecutor, QuantumExecutor) must treat
    this as the single source of truth for how a circuit will be executed.

    Attributes
    ----------
    backend : BackendChoice
        Which backend to use for execution.
    transpilation_strategy : TranspilationStrategy
        Which transpilation pipeline to apply before execution.
    params : dict
        Backend- and strategy-specific parameters, e.g.:
          {"max_bond_dim": 64, "optimization_level": 2, "shots": 1024}
    confidence : float
        Model confidence in [0, 1].  Values < 0.7 trigger rule fallback.
    reason : str
        Human-readable natural-language explanation of why this decision
        was made. Generated by the AIOptimizer.
    fallback_used : bool
        True if rule-based BackendSelector was used instead of AI model.
    source : DecisionSource
        Audit trail: which component produced this decision.
    feature_attribution : dict[str, float]
        Per-feature importance scores (from SHAP or manual attribution).
        Empty if not available.
    timestamp : float
        Unix timestamp at decision creation.
    decision_latency_ms : float
        Wall-clock time taken to produce this decision (ms).
    """

    backend: BackendChoice
    transpilation_strategy: TranspilationStrategy
    params: dict[str, Any]
    confidence: float
    reason: str
    fallback_used: bool = False
    source: DecisionSource = DecisionSource.AI_SUPERVISED
    feature_attribution: dict[str, float] = field(default_factory=dict)
    timestamp: float = field(default_factory=time.time)
    decision_latency_ms: float = 0.0

    # Convenience ------------------------------------------------------------

    @property
    def backend_str(self) -> str:
        """Return the raw string backend name for passing to executor."""
        return self.backend.value

    @property
    def strategy_str(self) -> str:
        return self.transpilation_strategy.value

    def to_dict(self) -> dict:
        """Serialisable dict for SQLite / JSON logging."""
        return {
            "backend": self.backend.value,
            "transpilation_strategy": self.transpilation_strategy.value,
            "params": self.params,
            "confidence": self.confidence,
            "reason": self.reason,
            "fallback_used": self.fallback_used,
            "source": self.source.value,
            "feature_attribution": self.feature_attribution,
            "timestamp": self.timestamp,
            "decision_latency_ms": self.decision_latency_ms,
        }

    def __str__(self) -> str:
        flag = " [FALLBACK]" if self.fallback_used else ""
        return (
            f"AIDecision{flag}("
            f"backend={self.backend.value}, "
            f"strategy={self.transpilation_strategy.value}, "
            f"confidence={self.confidence:.3f}, "
            f'reason="{self.reason}")'
        )


# ---------------------------------------------------------------------------
# Factory helpers
# ---------------------------------------------------------------------------

def make_emergency_decision() -> AIDecision:
    """
    Last-resort decision: statevector + rule-only transpilation.
    Used when all AI and rule-based paths raise exceptions.
    """
    return AIDecision(
        backend=BackendChoice.STATEVECTOR,
        transpilation_strategy=TranspilationStrategy.RULE_ONLY,
        params={"optimization_level": 1},
        confidence=0.0,
        reason="Emergency fallback: all decision paths failed. Defaulting to statevector.",
        fallback_used=True,
        source=DecisionSource.EMERGENCY,
    )
